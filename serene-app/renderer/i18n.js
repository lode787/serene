  function localeTag(code) {
    return LOCALE_TAGS[code] || LOCALE_TAGS.en;
  }

  function t(key, vars, lang) {
    const catalog = catalogs[lang] || catalogs.en;
    let str = (catalog && catalog[key]) || catalogs.en[key] || key;
    if (vars && typeof vars === 'object') {
      str = str.replace(/\{(\w+)\}/g, function (_, name) {
        return vars[name] != null ? String(vars[name]) : '{' + name + '}';
      });
    }
    return str;
  }

